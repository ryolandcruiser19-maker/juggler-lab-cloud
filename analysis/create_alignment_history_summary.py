import sqlite3
from pathlib import Path

import pandas as pd


# ============================================================
# DB設定
# ============================================================

BASE_DIR = Path(__file__).resolve().parent.parent
DB_PATH = BASE_DIR / "database" / "juggler.db"


# ============================================================
# メイン処理
# ============================================================

def main():

    print("========================================")
    print("alignment_history_analysis 作成開始")
    print("========================================")

    print(f"DB: {DB_PATH}")

    # --------------------------------------------------------
    # DB接続
    # --------------------------------------------------------

    conn = sqlite3.connect(DB_PATH)

    try:

        # ----------------------------------------------------
        # alignment_history 読み込み
        # ----------------------------------------------------

        print("alignment_history 読み込み開始")

        query = """
        SELECT
            日付,
            島,
            開始台番号,
            終了台番号,
            台数,
            ◎台数,
            ○台数,
            判定
        FROM alignment_history
        """

        df = pd.read_sql_query(query, conn)

        print(f"alignment_history 件数: {len(df)}")

        if df.empty:
            print("alignment_history にデータがありません。")
            return

        # ----------------------------------------------------
        # 数値型を明示
        # ----------------------------------------------------

        numeric_columns = [
            "開始台番号",
            "終了台番号",
            "台数",
            "◎台数",
            "○台数",
        ]

        for column in numeric_columns:
            df[column] = pd.to_numeric(
                df[column],
                errors="coerce"
            )

        # 数値変換できなかった行を除外
        df = df.dropna(
            subset=[
                "島",
                "開始台番号",
                "終了台番号",
                "台数",
                "◎台数",
                "○台数",
            ]
        ).copy()

        print(f"有効データ件数: {len(df)}")

        if df.empty:
            print("有効なalignment_historyデータがありません。")
            return

        # ----------------------------------------------------
        # 並びスコアを再計算
        #
        # 既存DBの「並びスコア」はBLOBになっているデータが
        # 存在するため、そこは使用しない。
        #
        # ◎ = 10点
        # ○ = 5点
        # ----------------------------------------------------

        df["並びスコア計算値"] = (
            df["◎台数"] * 10
            + df["○台数"] * 5
        )

        # ----------------------------------------------------
        # 強い並び判定
        #
        # 既存ロジック：
        # ◎3台なら「強い並び」
        # ----------------------------------------------------

        df["強い並び"] = (
            df["◎台数"] >= 3
        )

        # ----------------------------------------------------
        # 同一の並びを集計
        #
        # 集計単位：
        # 島 + 開始台番号 + 終了台番号
        # ----------------------------------------------------

        grouped = (
            df.groupby(
                [
                    "島",
                    "開始台番号",
                    "終了台番号",
                ],
                as_index=False
            )
            .agg(
                発生回数=("島", "size"),
                平均台数=("台数", "mean"),
                平均並びスコア=("並びスコア計算値", "mean"),
                強い並び回数=("強い並び", "sum"),
            )
        )

        # ----------------------------------------------------
        # 並び期待度
        #
        # 既存の1件
        #
        # 発生回数 = 1
        # 強い並び回数 = 0
        # 並び期待度 = 1.3
        #
        # と整合するように、
        #
        # 1.0
        # + 発生回数 × 0.3
        # + 強い並び回数 × 0.2
        #
        # とする。
        # ----------------------------------------------------

        grouped["並び期待度"] = (
            1.0
            + grouped["発生回数"] * 0.3
            + grouped["強い並び回数"] * 0.2
        )

        # ----------------------------------------------------
        # 型を整理
        # ----------------------------------------------------

        grouped["発生回数"] = (
            grouped["発生回数"]
            .astype(int)
        )

        grouped["強い並び回数"] = (
            grouped["強い並び回数"]
            .astype(int)
        )

        grouped["平均台数"] = (
            grouped["平均台数"]
            .round(1)
        )

        grouped["平均並びスコア"] = (
            grouped["平均並びスコア"]
            .round(1)
        )

        grouped["並び期待度"] = (
            grouped["並び期待度"]
            .round(1)
        )

        # ----------------------------------------------------
        # 列順をDBと合わせる
        # ----------------------------------------------------

        grouped = grouped[
            [
                "島",
                "開始台番号",
                "終了台番号",
                "発生回数",
                "平均台数",
                "平均並びスコア",
                "強い並び回数",
                "並び期待度",
            ]
        ]

        # ----------------------------------------------------
        # alignment_history_analysis 全削除
        # ----------------------------------------------------

        print(
            "alignment_history_analysis "
            "既存データ削除開始"
        )

        conn.execute(
            "DELETE FROM alignment_history_analysis"
        )

        conn.commit()

        # ----------------------------------------------------
        # 全件登録
        # ----------------------------------------------------

        print(
            "alignment_history_analysis "
            "登録開始"
        )

        grouped.to_sql(
            "alignment_history_analysis",
            conn,
            if_exists="append",
            index=False
        )

        conn.commit()

        # ----------------------------------------------------
        # 結果確認
        # ----------------------------------------------------

        count = conn.execute(
            """
            SELECT COUNT(*)
            FROM alignment_history_analysis
            """
        ).fetchone()[0]

        print()
        print("========================================")
        print("alignment_history_analysis 更新完了")
        print(f"登録件数: {count}")
        print("========================================")

        # ----------------------------------------------------
        # 上位データ表示
        #
        # 発生回数の多い順
        # 同数なら強い並び回数の多い順
        # ----------------------------------------------------

        result = pd.read_sql_query(
            """
            SELECT
                島,
                開始台番号,
                終了台番号,
                発生回数,
                平均台数,
                平均並びスコア,
                強い並び回数,
                並び期待度
            FROM alignment_history_analysis
            ORDER BY
                発生回数 DESC,
                強い並び回数 DESC,
                平均並びスコア DESC
            LIMIT 20
            """,
            conn
        )

        print()
        print("===== 発生回数上位20件 =====")
        print(result.to_string(index=False))

    finally:
        conn.close()


# ============================================================
# 実行
# ============================================================

if __name__ == "__main__":
    main()
