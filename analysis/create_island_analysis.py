"""
ジャグラーラボ
島分析作成

最新営業日の島ごとの状況を集計し、
island_analysis に登録する。
"""

import sqlite3
from pathlib import Path

import pandas as pd


# ============================================================
# DB設定
# ============================================================

BASE_DIR = Path(__file__).resolve().parent.parent

DB_PATH = (
    BASE_DIR
    / "database"
    / "juggler.db"
)


# ============================================================
# 島分析作成
# ============================================================

def create_island_analysis():

    print("=" * 60)
    print("島分析作成開始")
    print("=" * 60)

    print()
    print("DB:", DB_PATH)

    conn = sqlite3.connect(DB_PATH)

    try:

        # ====================================================
        # 最新営業日取得
        # ====================================================

        latest_date = pd.read_sql(
            """
            SELECT
                MAX(日付) AS 日付
            FROM daily_data
            """,
            conn,
        ).iloc[0]["日付"]

        print()
        print(
            "分析日:",
            latest_date
        )

        if pd.isna(latest_date):

            print(
                "daily_data にデータがありません。"
            )

            return

        # ====================================================
        # 最新日のデータ取得
        # ====================================================

        df = pd.read_sql(
            """
            SELECT
                *
            FROM daily_data
            WHERE 日付 = ?
            """,
            conn,
            params=[
                latest_date
            ],
        )

        print(
            "分析対象件数:",
            len(df)
        )

        if df.empty:

            print(
                "分析対象データがありません。"
            )

            return

        # ====================================================
        # 島別集計
        # ====================================================

        result = []

        for island, group in df.groupby("島"):

            # ------------------------------------------------
            # 台数
            # ------------------------------------------------

            count = int(
                len(group)
            )

            # ------------------------------------------------
            # 平均G数
            # ------------------------------------------------

            avg_game = float(
                group["G数"].mean()
            )

            # ------------------------------------------------
            # 平均合成確率
            # ------------------------------------------------

            avg_rate = (
                group["合成確率"]
                .dropna()
                .mean()
            )

            if pd.notna(avg_rate):

                avg_rate = float(
                    round(
                        avg_rate,
                        1
                    )
                )

            else:

                avg_rate = None

            # ------------------------------------------------
            # ◎台数
            # ------------------------------------------------

            high_count = int(
                group["評価"]
                .eq("◎")
                .sum()
            )

            # ------------------------------------------------
            # ○台数
            # ------------------------------------------------

            middle_count = int(
                group["評価"]
                .eq("○")
                .sum()
            )

            # ------------------------------------------------
            # 島評価スコア
            #
            # ◎ = 10点
            # ○ = 5点
            # ------------------------------------------------

            score = float(
                high_count * 10
                +
                middle_count * 5
            )

            # ------------------------------------------------
            # 結果
            # ------------------------------------------------

            result.append(
                (
                    latest_date,
                    island,
                    count,
                    float(
                        round(
                            avg_game,
                            1
                        )
                    ),
                    avg_rate,
                    high_count,
                    middle_count,
                    score,
                )
            )

        # ====================================================
        # 登録
        # ====================================================

        cursor = conn.cursor()

        for row in result:

            cursor.execute(
                """
                INSERT OR REPLACE INTO island_analysis
                (
                    日付,
                    島,
                    台数,
                    平均G数,
                    平均合成確率,
                    ◎台数,
                    ○台数,
                    評価スコア
                )
                VALUES
                (
                    ?, ?, ?, ?, ?, ?, ?, ?
                )
                """,
                row,
            )

        conn.commit()

        # ====================================================
        # 完了
        # ====================================================

        print()
        print("=" * 60)
        print("島分析登録完了")
        print("=" * 60)

        print(
            "分析日:",
            latest_date
        )

        print(
            "登録島数:",
            len(result)
        )

    finally:

        conn.close()


# ============================================================
# 実行
# ============================================================

if __name__ == "__main__":

    create_island_analysis()